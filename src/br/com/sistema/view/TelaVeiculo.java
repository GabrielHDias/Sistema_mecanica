    private void carregarClientes() {

        cbCliente.removeAllItems();

        ClienteDAO dao = new ClienteDAO();
        List<Cliente> clientes = dao.listar();

        for (Cliente cliente : clientes) {
            cbCliente.addItem(
                    cliente.getId() + " - " + cliente.getNome()
            );
        }

        cbCliente.setSelectedIndex(-1);
    }

    private int getClienteIdSelecionado() {

        String item = cbCliente.getSelectedItem().toString();

        String[] partes = item.split(" - ", 2);

        return Integer.parseInt(partes[0]);
    }

    private void limparCampos() {

        txtPlaca.setText("");
        txtModelo.setText("");
        txtMarca.setText("");

        cbCliente.setSelectedIndex(-1);
        tblVeiculos.clearSelection();

        txtPlaca.requestFocus();
    }

    private void atualizarTabela() {

        DefaultTableModel modelo
                = (DefaultTableModel) tblVeiculos.getModel();

        modelo.setRowCount(0);

        VeiculoDAO dao = new VeiculoDAO();
        List<Veiculo> veiculos = dao.listar();

        for (Veiculo veiculo : veiculos) {

            modelo.addRow(new Object[]{
                veiculo.getId(),
                veiculo.getPlaca(),
                veiculo.getModelo(),
                veiculo.getMarca(),
                getNomeCliente(veiculo.getClienteId())
            });
        }
    }

    private String getNomeCliente(int clienteId) {

        ClienteDAO dao = new ClienteDAO();
        List<Cliente> clientes = dao.listar();

        for (Cliente cliente : clientes) {

            if (cliente.getId() == clienteId) {
                return cliente.getNome();
            }
        }

        return "";
    }
