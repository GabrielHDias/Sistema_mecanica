    private boolean validarCampos() {

    String placa = txtPlaca.getText().trim().toUpperCase();
    String modelo = txtModelo.getText().trim();
    String marca = txtMarca.getText().trim();

    if (placa.isEmpty()
            || modelo.isEmpty()
            || marca.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos."
        );
        return false;
    }

    // Aceita:
    // ABC-1234  -> padrão antigo
    // ABC1234   -> padrão antigo sem hífen
    // ABC1D23   -> padrão Mercosul
    if (!placa.matches("^[A-Z]{3}(-?\\d{4}|\\d[A-Z]\\d{2})$")) {

        JOptionPane.showMessageDialog(
                this,
                "Placa inválida.\n"
                + "Use ABC-1234 ou ABC1D23."
        );

        txtPlaca.requestFocus();
        return false;
    }

    if (modelo.length() < 2) {

        JOptionPane.showMessageDialog(
                this,
                "Informe um modelo válido."
        );

        txtModelo.requestFocus();
        return false;
    }

    if (marca.length() < 2) {

        JOptionPane.showMessageDialog(
                this,
                "Informe uma marca válida."
        );

        txtMarca.requestFocus();
        return false;
    }

    if (cbCliente.getSelectedIndex() == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um cliente."
        );

        cbCliente.requestFocus();
        return false;
    }

    return true;
}

