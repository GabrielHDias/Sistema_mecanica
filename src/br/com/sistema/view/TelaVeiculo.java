    private void tblVeiculosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblVeiculosMouseClicked
        int linha = tblVeiculos.getSelectedRow();

        if (linha != -1) {

            txtPlaca.setText(
                    tblVeiculos.getValueAt(linha, 1).toString()
            );

            txtModelo.setText(
                    tblVeiculos.getValueAt(linha, 2).toString()
            );

            txtMarca.setText(
                    tblVeiculos.getValueAt(linha, 3).toString()
            );

            String nomeCliente
                    = tblVeiculos.getValueAt(linha, 4).toString();

            for (int i = 0; i < cbCliente.getItemCount(); i++) {

                String item = cbCliente.getItemAt(i);

                if (item.endsWith(" - " + nomeCliente)) {
                    cbCliente.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblVeiculosMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linha = tblVeiculos.getSelectedRow();

    if (linha == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um veículo na tabela."
        );

        return;
    }

    if (!validarCampos()) {
        return;
    }

    int id = Integer.parseInt(
            tblVeiculos.getValueAt(linha, 0).toString()
    );

    Veiculo veiculo = new Veiculo();

    veiculo.setId(id);

    veiculo.setPlaca(
            txtPlaca.getText().trim().toUpperCase()
    );

    veiculo.setModelo(
            txtModelo.getText().trim()
    );

    veiculo.setMarca(
            txtMarca.getText().trim()
    );

    veiculo.setClienteId(
            getClienteIdSelecionado()
    );

    VeiculoDAO dao = new VeiculoDAO();
    dao.editar(veiculo);

    JOptionPane.showMessageDialog(
            this,
            "Veículo editado com sucesso!"
    );

    atualizarTabela();
    limparCampos();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblVeiculos.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um veículo na tabela."
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir este veículo?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (resposta == JOptionPane.YES_OPTION) {

            int id = Integer.parseInt(
                    tblVeiculos.getValueAt(linha, 0).toString()
            );

            VeiculoDAO dao = new VeiculoDAO();
            if (dao.excluir(id)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Veículo excluído com sucesso!"
                );

                atualizarTabela();
                limparCampos();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Não é possível excluir este veículo.\n"
                        + "Existem serviços cadastrados para ele."
                );
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

