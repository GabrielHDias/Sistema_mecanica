    private void carregarVeiculos() {

        cbVeiculo.removeAllItems();

        VeiculoDAO dao = new VeiculoDAO();
        List<Veiculo> veiculos = dao.listar();

        for (Veiculo veiculo : veiculos) {

            cbVeiculo.addItem(
                    veiculo.getId()
                    + " - "
                    + veiculo.getPlaca()
                    + " - "
                    + veiculo.getMarca()
                    + " "
                    + veiculo.getModelo()
            );
        }

        cbVeiculo.setSelectedIndex(-1);
    }

    private int getVeiculoIdSelecionado() {

        String item = cbVeiculo.getSelectedItem().toString();

        String[] partes = item.split(" - ", 2);

        return Integer.parseInt(partes[0]);
    }

    private boolean validarCampos() {

        String descricao = txtDescricao.getText().trim();
        String valorTexto = txtValor.getText().trim();
        String dataTexto = txtData.getText().trim();

        if (descricao.isEmpty()
                || valorTexto.isEmpty()
                || dataTexto.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos."
            );

            return false;
        }

        if (descricao.length() < 3) {

            JOptionPane.showMessageDialog(
                    this,
                    "A descrição deve possuir pelo menos 3 caracteres."
            );

            txtDescricao.requestFocus();
            return false;
        }

        try {

            BigDecimal valor
                    = new BigDecimal(valorTexto.replace(",", "."));

            if (valor.compareTo(BigDecimal.ZERO) <= 0) {

                JOptionPane.showMessageDialog(
                        this,
                        "O valor deve ser maior que zero."
                );

                txtValor.requestFocus();
                return false;
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Informe um valor válido."
            );

            txtValor.requestFocus();
            return false;
        }

        try {

            Date.valueOf(dataTexto);

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Data inválida.\nUse o formato AAAA-MM-DD."
            );

            txtData.requestFocus();
            return false;
        }

        if (cbVeiculo.getSelectedIndex() == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um veículo."
            );

            cbVeiculo.requestFocus();
            return false;
        }

        return true;
    }
