    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

        if (!validarCampos()) {
            return;
        }

        Servico servico = new Servico();

        servico.setDescricao(
                txtDescricao.getText().trim()
        );

        servico.setValor(
                new BigDecimal(
                        txtValor.getText().trim().replace(",", ".")
                )
        );

        servico.setDataServico(
                Date.valueOf(txtData.getText().trim())
        );

        servico.setVeiculoId(
                getVeiculoIdSelecionado()
        );

        ServicoDAO dao = new ServicoDAO();
        dao.salvar(servico);

        JOptionPane.showMessageDialog(
                this,
                "Serviço cadastrado com sucesso!"
        );

        atualizarTabela();
        limparCampos();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed
        limparCampos();
    }//GEN-LAST:event_btnLimparActionPerformed

    private void tblServicosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblServicosMouseClicked

        int linha = tblServicos.getSelectedRow();

        if (linha != -1) {

            txtDescricao.setText(
                    tblServicos.getValueAt(linha, 1).toString()
            );

            txtValor.setText(
                    tblServicos.getValueAt(linha, 2).toString()
            );

            txtData.setText(
                    tblServicos.getValueAt(linha, 3).toString()
            );

            String descricaoVeiculo
                    = tblServicos.getValueAt(linha, 4).toString();

            for (int i = 0; i < cbVeiculo.getItemCount(); i++) {

                String item = cbVeiculo.getItemAt(i);

                if (item.endsWith(descricaoVeiculo)) {
                    cbVeiculo.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblServicosMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int linha = tblServicos.getSelectedRow();

        if (linha == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um serviço na tabela."
            );

            return;
        }

        if (!validarCampos()) {
            return;
        }

        int id = Integer.parseInt(
                tblServicos.getValueAt(linha, 0).toString()
        );

        Servico servico = new Servico();

        servico.setId(id);

        servico.setDescricao(
                txtDescricao.getText().trim()
        );

        servico.setValor(
                new BigDecimal(
                        txtValor.getText().trim().replace(",", ".")
                )
        );

        servico.setDataServico(
                Date.valueOf(txtData.getText().trim())
        );

        servico.setVeiculoId(
                getVeiculoIdSelecionado()
        );

        ServicoDAO dao = new ServicoDAO();
        dao.editar(servico);

        JOptionPane.showMessageDialog(
                this,
                "Serviço editado com sucesso!"
        );

        atualizarTabela();
        limparCampos();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblServicos.getSelectedRow();

        if (linha == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um serviço na tabela."
            );

            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir este serviço?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (resposta == JOptionPane.YES_OPTION) {

            int id = Integer.parseInt(
                    tblServicos.getValueAt(linha, 0).toString()
            );

            ServicoDAO dao = new ServicoDAO();
            dao.excluir(id);

            JOptionPane.showMessageDialog(
                    this,
                    "Serviço excluído com sucesso!"
            );

            atualizarTabela();
            limparCampos();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed
    private void limparCampos() {

        txtDescricao.setText("");
        txtValor.setText("");
        txtData.setText("");

        cbVeiculo.setSelectedIndex(-1);
        tblServicos.clearSelection();

        txtDescricao.requestFocus();
    }

    private void atualizarTabela() {

        DefaultTableModel modelo
                = (DefaultTableModel) tblServicos.getModel();

        modelo.setRowCount(0);

        ServicoDAO dao = new ServicoDAO();
        List<Servico> servicos = dao.listar();

        for (Servico servico : servicos) {

            modelo.addRow(new Object[]{
                servico.getId(),
                servico.getDescricao(),
                servico.getValor(),
                servico.getDataServico(),
                getDescricaoVeiculo(servico.getVeiculoId())
            });
        }
    }

    private String getDescricaoVeiculo(int veiculoId) {

        VeiculoDAO dao = new VeiculoDAO();
        List<Veiculo> veiculos = dao.listar();

        for (Veiculo veiculo : veiculos) {

            if (veiculo.getId() == veiculoId) {

                return veiculo.getPlaca()
                        + " - "
                        + veiculo.getMarca()
                        + " "
                        + veiculo.getModelo();
            }
        }

        return "";
    }

