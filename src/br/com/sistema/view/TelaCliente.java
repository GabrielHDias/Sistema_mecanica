    private void atualizarTabela() {

        DefaultTableModel modelo
                = (DefaultTableModel) tblClientes.getModel();

        modelo.setRowCount(0);

        ClienteDAO dao = new ClienteDAO();
        List<Cliente> clientes = dao.listar();

        for (Cliente cliente : clientes) {

            modelo.addRow(new Object[]{
                cliente.getId(),
                cliente.getNome(),
                cliente.getCpf(),
                cliente.getTelefone()
            });
        }
    }

    private void limparCampos() {
        txtNome.setText("");
        txtCpf.setText("");
        txtTelefone.setText("");

        tblClientes.clearSelection();

        txtNome.requestFocus();
    }

    private boolean validarNome() {

        String nome = txtNome.getText().trim();

        if (nome.length() < 3) {
            JOptionPane.showMessageDialog(
                    this,
                    "O nome deve possuir pelo menos 3 caracteres."
            );
            txtNome.requestFocus();
            return false;
        }

        if (!nome.matches("[\\p{L}\\s]+")) {
            JOptionPane.showMessageDialog(
                    this,
                    "O nome deve conter apenas letras e espaços."
            );
            txtNome.requestFocus();
            return false;
        }

        return true;
    }

    private boolean validarCpf() {

        String cpf = txtCpf.getText().trim();

        if (!cpf.matches("\\d{3}\\.\\d{3}\\.\\d{3}-\\d{2}")) {

            JOptionPane.showMessageDialog(
                    this,
                    "CPF inválido.\nUse o formato 000.000.000-00."
            );

            txtCpf.requestFocus();
            return false;
        }

        return true;
    }

    private boolean validarTelefone() {

        String telefone = txtTelefone.getText().trim();

        if (!telefone.matches("\\(\\d{2}\\) \\d{5}-\\d{4}")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Telefone inválido.\nUse o formato (00) 00000-0000."
            );

            txtTelefone.requestFocus();
            return false;
        }

        return true;
    }

    private boolean validarCampos() {

        if (txtNome.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Preencha o nome."
            );

            txtNome.requestFocus();
            return false;
        }

        if (!validarNome()) {
            return false;
        }

        if (!validarCpf()) {
            return false;
        }

        if (!validarTelefone()) {
            return false;
        }

        return true;
    }

    private void aplicarMascaras() {

        try {

            MaskFormatter mascaraCpf
                    = new MaskFormatter("###.###.###-##");

            mascaraCpf.setPlaceholderCharacter('_');
            mascaraCpf.install(txtCpf);

            MaskFormatter mascaraTelefone
                    = new MaskFormatter("(##) #####-####");

            mascaraTelefone.setPlaceholderCharacter('_');
            mascaraTelefone.install(txtTelefone);

        } catch (ParseException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao configurar máscaras."
            );
        }
    }
